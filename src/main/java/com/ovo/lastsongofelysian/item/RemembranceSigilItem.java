    private final int stars;

    public RemembranceSigilItem(Properties properties, int stars) {
        super(properties);
        this.stars = stars;
    }

    @Override
    public boolean canEquip(SlotContext slotContext, ItemStack stack) {
        if (stars != 4) {
            return true;
        }

        return CuriosApi.getCuriosHelper()
                .findFirstCurio(
                        slotContext.entity(),
                        equipped -> equipped.getItem() instanceof RemembranceSigilItem sigil
                                && sigil.stars == 4
                )
                .isEmpty();
    }

    @Override
    public void appendHoverText(ItemStack stack, @Nullable Level level, List<Component> tooltip, TooltipFlag flag) {
        tooltip.add(ModText.literal("星级：" + "★".repeat(stars))
                .withStyle(ChatFormatting.GOLD));

        String itemId = BuiltInRegistries.ITEM.getKey(stack.getItem()).getPath();
        LoreDefinition lore = getLore(itemId);
        if (lore != null) {
            Style deep = Style.EMPTY
                    .withColor(TextColor.fromRgb(lore.deepColor()))
                    .withBold(true);
            Style light = Style.EMPTY
                    .withColor(TextColor.fromRgb(lore.lightColor()));
            Style dialogue = light.withItalic(true);

            tooltip.add(Component.empty());
            boolean inDialogue = false;
            for (int i = 0; i < lore.lines().length; i++) {
                String line = lore.lines()[i];
                if (line.startsWith("——")) {
                    inDialogue = true;
                }
                tooltip.add(line.isEmpty()
                        ? Component.empty()
                        : ModText.literal(line).withStyle(
                                i == 0 ? deep : inDialogue ? dialogue : light));
            }
        }

        super.appendHoverText(stack, level, tooltip, flag);
    }

